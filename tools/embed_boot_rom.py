#!/usr/bin/env python3
"""Regenerate the private Opera Boot header; not required for normal builds."""

import argparse
import hashlib
from pathlib import Path
import zlib


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "rom", nargs="?", type=Path, default=Path("opera-boot.bin"),
        help="source ROM (default: opera-boot.bin)",
    )
    parser.add_argument(
        "output", nargs="?", type=Path, default=Path("opera_boot.h"),
        help="destination header (default: opera_boot.h)",
    )
    args = parser.parse_args()
    source = args.rom.read_bytes()
    compressed = zlib.compress(source, level=9)
    rows = [
        "#pragma once",
        "",
        "#include <stdint.h>",
        "",
        "// Generated by tools/embed_boot_rom.py; do not edit by hand.",
        "// Source: opera-boot project: https://github.com/trapexit/opera-boot",
        "// Source license: GPL-2.0-only.",
        f"// Source bytes: {len(source)}; CRC32: {zlib.crc32(source):08x}.",
        f"// Source SHA256: {hashlib.sha256(source).hexdigest()}.",
        f"// Compression: zlib wrapper, level 9; compressed bytes: {len(compressed)}.",
        "",
        f"enum {{ OPERA_BOOT_ROM_BYTES = {len(source)} }};",
        "",
        "static const uint8_t OPERA_BOOT_ZLIB[] =",
        "  {",
    ]
    
    for offset in range(0, len(compressed), 12):
        row = ", ".join(f"0x{byte:02x}" for byte in compressed[offset:offset + 12])
        rows.append(f"    {row},")
    rows.extend(["  };", ""])
    args.output.write_text("\n".join(rows), encoding="utf-8", newline="\n")
    print(f"{len(source)} source bytes -> {len(compressed)} compressed bytes")
    print(f"SHA256 {hashlib.sha256(source).hexdigest()}")


if __name__ == "__main__":
    main()
